"""Turn a mod's hooks.json into the C table the IL2CPP runtime (runtime/) reads.

Usage: python3 scripts/embed_hooks.py <hooks.json> <out.c>

scripts/build.sh runs it for a mod that has a hooks.json and compiles the result into the tweak, so the
installed game needs no extra file. The file is checked the way scripts/validate_mods.py checks it.

A game that hides every il2cpp_* name adds a "table" section:

    "table": {
        "registration_rva": "0x5593a48",
        "dump": "C:/AccretionMods/work/dump-<mod>-<ver>/dump.cs",
        "binary": "C:/AccretionMods/work/<game>/UnityFramework",
        "module": "Assembly-CSharp.dll"
    }

The build then resolves every hooks.json method to (Il2CppCodeGenModule, methodPointers index) with
scripts/table_hooks.py, writes TableHooks.gen.h next to <out.c>, and the runtime hooks the table before
IL2CPP initialises its MethodInfos (runtime/AMTableHook.c). The paths may also come from
--dump/--binary/--registration on the command line.
"""

import argparse
import json
import sys
from pathlib import Path

try:  # run as a script (scripts/build.sh) or imported as scripts.embed_hooks (tests)
    import table_hooks
    from hide import c_bytes
    from validate_mods import hooks_problems
except ModuleNotFoundError:
    from scripts import table_hooks
    from scripts.hide import c_bytes
    from scripts.validate_mods import hooks_problems


def render(data, table=False):
    """The hooks as a C table. The names are encoded (runtime/am_hide.h): am_hook_specs_reveal() decodes them in
    place before the runtime reads the table, so the .dylib carries no plain class or method name.

    table=True: the generated TableHooks.gen.h is included and its specs become am_hook_table_specs, so
    AMIl2cppStart takes the data-table path (a game without il2cpp_* exports)."""
    lines = ["// Generated by scripts/embed_hooks.py from hooks.json. Do not edit.",
             '#include "am_il2cpp.h"', '#include "am_hide.h"', '#include "AMTableHook.h"', ""]
    if table:
        lines.append('#include "TableHooks.gen.h"')
        lines.append("AMTableHookSpec *am_hook_table_specs = AMTableHooks;")
        lines.append("const size_t am_hook_table_count = AM_TABLE_HOOK_COUNT;")
        lines.append("const uint64_t am_hook_table_registration = AM_TABLE_REGISTRATION_RVA;")
    else:
        lines.append("AMTableHookSpec *am_hook_table_specs = 0;")
        lines.append("const size_t am_hook_table_count = 0;")
        lines.append("const uint64_t am_hook_table_registration = 0;")
    lines.append("")
    fields = ("assembly", "namespace", "class", "method")
    for i, h in enumerate(data["hooks"]):
        for k, f in enumerate(fields):
            lines.append(f"static char h{i}_{k}[] = {c_bytes(h.get(f, ''))};")
    lines.append("")
    lines.append("const AMHookSpec am_hook_specs[] = {")
    for i, h in enumerate(data["hooks"]):
        lines.append(f"    {{h{i}_0, h{i}_1, h{i}_2, h{i}_3, {h.get('args', -1)}}},")
    if not data["hooks"]:
        lines.append("    {\"\", \"\", \"\", \"\", -1},  // empty table is not valid C")
    lines.append("};")
    lines.append(f"const size_t am_hook_spec_count = {len(data['hooks'])};")
    lines.append("")
    lines.append("// decodes every name once, in place (AMIl2cpp.m calls it before installing)")
    lines.append("void am_hook_specs_reveal(void) {")
    lines.append("    static int done;")
    lines.append("    if (done) return;")
    lines.append("    done = 1;")
    for i, h in enumerate(data["hooks"]):
        for k, f in enumerate(fields):
            n = len(h.get(f, "").encode("utf-8"))
            lines.append(f"    am_unhide(h{i}_{k}, (const unsigned char *)h{i}_{k}, {n});")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("hooks_json")
    parser.add_argument("out_c")
    parser.add_argument("--dump")
    parser.add_argument("--binary")
    parser.add_argument("--registration")
    parser.add_argument("--module")
    args = parser.parse_args(argv)
    src, dest = args.hooks_json, args.out_c
    problems = hooks_problems(src)
    if problems:
        sys.exit("hooks.json: " + "; ".join(problems))
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    table = data.get("table")
    generated = False
    if table:
        registration = args.registration or table.get("registration_rva")
        dump = args.dump or table.get("dump")
        binary = args.binary or table.get("binary")
        module = args.module or table.get("module")
        if not (registration and dump and binary):
            sys.exit('hooks.json "table" needs registration_rva, dump and binary (or --registration/--dump/--binary)')
        names = [f"{h.get('class', '')}.{h.get('method', '')}" for h in data["hooks"]]
        pins = data.get("pins") or []
        pin_names = [f"{p.get('class', '')}.{p.get('method', '')}" for p in pins]
        result = table_hooks.generate(dump, binary, int(str(registration), 0), names + pin_names, module)
        if pins:
            fields = table_hooks.parse_fields(Path(dump).read_text(errors="ignore"))
            by_full = {f.full_name: f for f in fields}
            by_short = {f"{f.klass}.{f.name}": f for f in fields}
            resolved = []
            for i, pin in enumerate(pins):
                key = f"{pin.get('class', '')}.{pin.get('field', '')}"
                field = by_full.get(key) or by_short.get(key)
                if field is None:
                    sys.exit(f"pin {i}: field {key} is not in {dump}")
                resolved.append({
                    "name": pin_names[i],
                    "module": result["hooks"][len(names) + i]["module"],
                    "index": result["hooks"][len(names) + i]["index"],
                    "offset": field.offset,
                    "type": pin.get("type") or "",
                    "value": pin.get("value"),
                })
            header_text = table_hooks.header_with_pins(
                {"registration_rva": result["registration_rva"], "hooks": result["hooks"][:len(names)]}, resolved)
        else:
            header_text = table_hooks.header(result)
        header_path = Path(dest).with_name("TableHooks.gen.h")
        header_path.write_text(header_text, encoding="utf-8", newline="\n")
        print(f"{len(result['hooks'])} table hooks ({len(pins)} pins) -> {header_path}", file=sys.stderr)
        generated = True
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(data, generated))
    print(f"{len(data['hooks'])} hooks -> {dest}")


if __name__ == "__main__":
    main()

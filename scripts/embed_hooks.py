"""Turn a mod's hooks.json into the C table the IL2CPP runtime (runtime/) reads.

Usage: python3 scripts/embed_hooks.py <hooks.json> <out.c>

scripts/build.sh runs it for a mod that has a hooks.json and compiles the result into the tweak, so the
installed game needs no extra file. The file is checked the way scripts/validate_mods.py checks it.
"""

import json
import sys

from validate_mods import hooks_problems


def c_string(text):
    out = []
    for ch in text:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("".join(f"\\{b:03o}" for b in ch.encode("utf-8")))
    return '"' + "".join(out) + '"'


def render(data):
    lines = ["// Generated by scripts/embed_hooks.py from hooks.json. Do not edit.", '#include "am_il2cpp.h"', ""]
    lines.append("const AMHookSpec am_hook_specs[] = {")
    for h in data["hooks"]:
        lines.append(
            f"    {{{c_string(h.get('assembly', ''))}, {c_string(h['namespace'])}, {c_string(h['class'])}, "
            f"{c_string(h['method'])}, {h.get('args', -1)}}},"
        )
    if not data["hooks"]:
        lines.append("    {\"\", \"\", \"\", \"\", -1},  // empty table is not valid C")
    lines.append("};")
    lines.append(f"const size_t am_hook_spec_count = {len(data['hooks'])};")
    return "\n".join(lines) + "\n"


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        sys.exit(__doc__)
    src, dest = argv
    problems = hooks_problems(src)
    if problems:
        sys.exit("hooks.json: " + "; ".join(problems))
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(data))
    print(f"{len(data['hooks'])} hooks -> {dest}")


if __name__ == "__main__":
    main()

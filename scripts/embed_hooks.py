"""Turn a mod's hooks.json into runtime/am_hooks_data.c, the C table runtime/AMIl2cpp.m reads.

Usage: python3 scripts/embed_hooks.py <hooks.json> <out.c> [--dump dump.cs --binary UnityFramework
                                                           --registration 0x... --module Assembly-CSharp.dll]

scripts/build.sh runs it for a mod that has a hooks.json and compiles the result into the tweak, so the
installed game needs no extra file. The file is checked the way scripts/validate_mods.py checks it.

A game that hides every il2cpp_* name adds a "table" section:

    "table": {
        "registration_rva": "0x5593a48",
        "dump": "C:/AccretionMods/work/dump-<mod>-<ver>/dump.cs",
        "binary": "C:/AccretionMods/work/<game>/UnityFramework",
        "module": "Assembly-CSharp.dll"
    }

The build then resolves every hooks.json method (and every pin's method) to (Il2CppCodeGenModule,
methodPointers index) with scripts/table_hooks.py and writes them into <out.c> as am_hook_table_specs; the
runtime patches the table before IL2CPP initialises its MethodInfos (runtime/AMTableHook.c). The paths may
also come from --dump/--binary/--registration on the command line (scripts/build.sh passes the dump
scripts/dev.py made). A pin's method must be an instance method with no parameters that returns void, like
Update: the generated replacement writes the field, then calls the original with (self, method).
"""

import argparse
import json
import sys
from pathlib import Path

import table_hooks
from hide import c_bytes
from validate_mods import hooks_problems


def spec_name(entry):
    """The name AMIl2cppRegister uses: Namespace.Class.Method, or Class.Method in the global namespace."""
    namespace = entry.get("namespace", "")
    base = f"{entry.get('class', '')}.{entry.get('method', '')}"
    return f"{namespace}.{base}" if namespace else base


def render(data, table=None, pins=None):
    """The hooks as a C table. The names are encoded (runtime/am_hide.h): am_hook_specs_reveal() decodes them in
    place before the runtime reads the table, so the .dylib carries no plain class or method name.

    table: the result of table_hooks.generate() for the hooks (and pins) of a game without il2cpp_* exports;
    its entries become am_hook_table_specs, with the same encoded names, so AMIl2cppStart takes the
    data-table path. pins: the resolved pins ({name, module, index, offset, type, value}) whose replacements
    table_hooks.pin_stubs() writes."""
    pins = pins or []
    lines = ["// Generated by scripts/embed_hooks.py from hooks.json. Do not edit.",
             '#include "am_il2cpp.h"', '#include "am_hide.h"', '#include "AMTableHook.h"', ""]
    fields = ("assembly", "namespace", "class", "method")
    for i, h in enumerate(data["hooks"]):
        for k, f in enumerate(fields):
            lines.append(f"static char h{i}_{k}[] = {c_bytes(h.get(f, ''))};")
    lines.append("")
    lines.append("const AMHookSpec am_hook_specs[] = {")
    for i, h in enumerate(data["hooks"]):
        lines.append(f"    {{h{i}_0, h{i}_1, h{i}_2, h{i}_3, {h.get('args', -1)}}},")
    if not data["hooks"]:
        lines.append("    {\"\", \"\", \"\", \"\", -1},  // empty table is not valid C")
    lines.append("};")
    lines.append(f"const size_t am_hook_spec_count = {len(data['hooks'])};")
    lines.append("")
    table_names = []
    if table:
        # hooks.json "table": the entries scripts/table_hooks.py resolved, names encoded like the hooks'
        table_names = [h["name"] for h in table["hooks"]] + [p["name"] for p in pins]
        for i, name in enumerate(table_names):
            lines.append(f"static char t{i}[] = {c_bytes(name)};")
        lines += table_hooks.pin_stubs(pins)
        lines.append("static AMTableHookSpec am_table_hooks[] = {")
        lines += table_hooks.spec_lines(table, pins, lambda i, name: f"t{i}")
        lines.append("};")
        lines.append("AMTableHookSpec *am_hook_table_specs = am_table_hooks;")
        lines.append(f"const size_t am_hook_table_count = {len(table_names)};")
        lines.append(f"const uint64_t am_hook_table_registration = {table['registration_rva']:#x}ULL;")
        lines.append(f"const uint32_t am_hook_table_modules_offset = {table['modules_offset']};")
    else:
        lines.append("AMTableHookSpec *am_hook_table_specs = 0;")
        lines.append("const size_t am_hook_table_count = 0;")
        lines.append("const uint64_t am_hook_table_registration = 0;")
        lines.append("const uint32_t am_hook_table_modules_offset = 0;")
    lines.append("")
    lines.append("// decodes every name once, in place (AMIl2cpp.m calls it before installing)")
    lines.append("void am_hook_specs_reveal(void) {")
    lines.append("    static int done;")
    lines.append("    if (done) return;")
    lines.append("    done = 1;")
    for i, h in enumerate(data["hooks"]):
        for k, f in enumerate(fields):
            n = len(h.get(f, "").encode("utf-8"))
            lines.append(f"    am_unhide(h{i}_{k}, (const unsigned char *)h{i}_{k}, {n});")
    for i, name in enumerate(table_names):
        lines.append(f"    am_unhide(t{i}, (const unsigned char *)t{i}, {len(name.encode('utf-8'))});")
    lines.append("}")
    return "\n".join(lines) + "\n"


def resolve_table(data, dump, binary, registration, module=None, reader=None):
    """(table, pins) for render(): every hook and pin of hooks.json resolved against the dump and the binary.
    Exits with the first method or field that is missing, or a pin whose method a pin replacement can't wrap."""
    hooks = data["hooks"]
    pins = data.get("pins") or []
    names = [spec_name(h) for h in hooks] + [spec_name(p) for p in pins]
    result = table_hooks.generate(dump, binary, registration, names, module, reader)
    resolved = []
    if pins:
        fields = table_hooks.parse_fields(Path(dump).read_text(errors="ignore"))
        for i, pin in enumerate(pins):
            entry = result["hooks"][len(hooks) + i]
            problem = table_hooks.pin_problem(entry["method"])
            if problem:
                sys.exit(f"pin {i}: {entry['name']} {problem}: {entry['method'].signature}")
            key = f"{pin.get('class', '')}.{pin.get('field', '')}"
            namespace = pin.get("namespace", "")
            found = table_hooks.find_field(fields, f"{namespace}.{key}" if namespace else key)
            if found is None:
                sys.exit(f"pin {i}: field {key} is not in {dump} (the dump needs field offsets)")
            resolved.append({
                "name": entry["name"],
                "module": entry["module"],
                "index": entry["index"],
                "offset": found.offset,
                "type": pin.get("type") or "",
                "value": pin.get("value"),
            })
    return {**result, "hooks": result["hooks"][:len(hooks)]}, resolved


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("hooks_json")
    parser.add_argument("out_c")
    parser.add_argument("--dump")
    parser.add_argument("--binary")
    parser.add_argument("--registration")
    parser.add_argument("--module")
    args = parser.parse_args(argv)
    src, dest = args.hooks_json, args.out_c
    problems = hooks_problems(src)
    if problems:
        sys.exit("hooks.json: " + "; ".join(problems))
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    table = data.get("table")
    resolved = pins = None
    if table:
        registration = args.registration or table.get("registration_rva")
        dump = args.dump or table.get("dump")
        binary = args.binary or table.get("binary")
        module = args.module or table.get("module")
        if not (registration and dump and binary):
            sys.exit('hooks.json "table" needs registration_rva, dump and binary (or --registration/--dump/--binary)')
        resolved, pins = resolve_table(data, dump, binary, int(str(registration), 0), module)
        print(f"{len(resolved['hooks'])} table hooks, {len(pins)} pins (codeGenModules at +{resolved['modules_offset']})",
              file=sys.stderr)
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(data, resolved, pins))
    print(f"{len(data['hooks'])} hooks -> {dest}")


if __name__ == "__main__":
    main()
